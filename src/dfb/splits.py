"""On the real data: leakage rules and per-split counts.

Writes reports/splits.md. The counts are part of the frozen benchmark: anyone rebuilding the data must get the same numbers.
"""

from __future__ import annotations

import duckdb

from . import config
from .features import FEATURES_DIR
from .labels import WINDOWS, usable_sql
from .leakage import LeakageError


def glob(period: str) -> str:
    return f"read_parquet('{FEATURES_DIR}/{period}/*/*.parquet')"


def summarize() -> str:
    con = duckdb.connect()
    try:
        con.execute("SET enable_progress_bar=false")
    except duckdb.InvalidInputException:  # inside Jupyter without ipywidgets
        pass
    lines = ["# Splits and leakage check", "",
             "Generated by `dfb splits` from `data/features/`. Data hard drives only (R-1).", "",
             "## Leakage rules checked on the real data", ""]
    prev_end = None
    for period in ("train", "valid", "test"):
        start, end = config.PERIODS[period]
        lo, hi, tags = con.execute(
            f"SELECT min(date), max(date), count(DISTINCT period) FROM {glob(period)}").fetchone()
        lo, hi = lo.date() if hasattr(lo, "date") else lo, hi.date() if hasattr(hi, "date") else hi
        if lo < start or hi > end or tags != 1:
            raise LeakageError(f"{period}: dates {lo}..{hi} not inside {start}..{end}")
        if prev_end is not None and lo <= prev_end:
            raise LeakageError(f"{period} starts before the previous period ends")
        lines.append(f"- {period}: every date inside {start} to {end} (found {lo} to {hi}); "
                     "one period tag")
        prev_end = hi
        after = con.execute(f"SELECT count(*) FROM {glob(period)} WHERE days_to_failure < 0").fetchone()[0]
        if after:
            raise LeakageError(f"{period}: {after} rows after a drive's failure")
    lines.append("- no row falls after its drive's failure date")
    lines.append("- labels: a row is used only if its N-day label is decided inside its "
                 "own period (the window ends inside it, or the drive fails inside both the "
                 "window and the period); counts below are after that rule (L-2)")
    lines += ["", "## Counts per split", "",
              "| split | N (days) | rows used | drives | failed drives in split | "
              "positive rows | weighted share positive |",
              "|---|---|---|---|---|---|---|"]
    for period in ("train", "valid", "test"):
        for n in WINDOWS:
            r = con.execute(f"""
                SELECT count(*), count(DISTINCT serial_number),
                       count(DISTINCT serial_number) FILTER (WHERE days_to_failure = 0),
                       count(*) FILTER (WHERE days_to_failure BETWEEN 0 AND {n - 1}),
                       sum(sample_weight * (days_to_failure BETWEEN 0 AND {n - 1})::INT)
                         / sum(sample_weight)
                FROM {glob(period)} WHERE {usable_sql(n)}""").fetchone()
            lines.append(f"| {period} | {n} | {r[0]:,} | {r[1]:,} | {r[2]:,} | {r[3]:,} | "
                         f"{r[4] * 100:.4f}% |")
    lines += ["", "Training rows are the F-12 sample (sampled days weigh 50); validation and "
              "test hold every day. \"Failed drives in split\" counts drives whose failure day "
              "is inside the split's usable rows.", ""]
    text = "\n".join(lines)
    config.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (config.REPORTS_DIR / "splits.md").write_text(text)
    return text
